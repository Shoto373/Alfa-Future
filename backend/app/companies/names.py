SUFFIXES = ["", " Групп", " Холдинг", " Трейд", "-Сибирь", " Плюс", "-Юг", " Северо-Запад", "-Инвест", " Онлайн",
            "-Урал", " Восток", " Про", "-Волга", " Интер"]
FORMS = ["ООО", "ООО", "ООО", "АО", "АО", "ПАО"]


def _hash(company_id: str) -> int:
    return int(hashlib.sha1(company_id.encode()).hexdigest()[:8], 16)


def assign(companies: list[dict]) -> None:
    """Проставляет display_name всем компаниям; уникальность — в порядке company_id."""
    taken: set[str] = set()
    for c in sorted(companies, key=lambda x: x["company_id"]):
        h = _hash(c["company_id"])
        roots = ROOTS.get(c.get("sector"), ROOTS["other"])
        form = FORMS[h % len(FORMS)]
        name = None
        for i in range(len(roots) * len(SUFFIXES)):
            root = roots[(h + i) % len(roots)]
            suffix = SUFFIXES[((h // 7) + i // len(roots)) % len(SUFFIXES)]
            candidate = f"{form} «{root}{suffix}»"
            if candidate not in taken:
                name = candidate
                break
        if name is None:  # в отрасли больше компаний, чем комбинаций, — добавляем номер
            name = f"{form} «{roots[h % len(roots)]} {c['company_id'].replace('U_', '')}»"
        taken.add(name)
        c["display_name"] = name
