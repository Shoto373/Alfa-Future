"""Explicit, idempotent import of an existing JSON runtime into PostgreSQL.

Source files are read only. Imported insights are archived with an obsolete
cache version; new requests are regenerated by the current checked pipeline.
The whole import commits together or rolls back on invalid references.

Учетные записи (users.json, memberships.json, sessions.json) переносятся в таблицы users,
memberships и sessions: email — в нижнем регистре (дубликаты по регистру сливаются в первую
запись), пароли — как есть (старые хэши проверяются и перехэшируются при входе), живые сессии
сохраняются. При старте сервиса перенос выполняется один раз сам (import_auth_once).
"""
import argparse
import hashlib
import json
from pathlib import Path
from datetime import datetime, timedelta, timezone

from sqlalchemy import select, func
from sqlalchemy.dialects.postgresql import insert
from app.models import AuthMembership, AuthSession, AuthUser, Company, News, Insight, Feedback, Event, ToolAudit

from app import config, database
from app.auth import security


def import_runtime(root: Path) -> dict:
    root = root.resolve(strict=True)
    counts = {"companies": 0, "news": 0, "insights": 0, "feedback": 0, "events": 0, "audit": 0}
    def read(path):
        return json.loads(path.read_text(encoding="utf-8"))
    with database.session() as db:
        db.execute(select(func.pg_advisory_xact_lock(72810405)))
        path = root / "companies.json"
        if path.exists():
            for c in read(path)["companies"]:
                counts["companies"] += db.execute(insert(Company).values(company_id=c["company_id"],
                    sector=c["sector"], revenue=c.get("revenue"), payload=c).on_conflict_do_nothing()).rowcount
        path = root / "news.json"
        if path.exists():
            for n in read(path):
                counts["news"] += db.execute(insert(News).values(news_id=n["news_id"],
                    published_at=datetime.fromisoformat(n["published_at"]), kind=n["kind"], payload=n)
                    .on_conflict_do_nothing()).rowcount
        for path in sorted((root / "insights").glob("ins-*.json")):
            ins = read(path)
            ins["quality"] = {"passed": False, "attempts": ins.get("quality", {}).get("attempts", 1), "checks": [
                {"name": "legacy_import", "passed": False, "detail": "Архивный разбор; требуется пересчет текущей версией"}]}
            counts["insights"] += db.execute(insert(Insight).values(insight_id=ins["insight_id"],
                company_id=ins["company_id"], news_id=ins["news_id"], role=ins["role"],
                created_at=datetime.fromisoformat(ins["created_at"]), cache_version="legacy", payload=ins)
                .on_conflict_do_nothing()).rowcount
        for filename, table in (("feedback.jsonl", "feedback"), ("events.jsonl", "events"), ("audit.jsonl", "audit")):
            path = root / filename
            if not path.exists():
                continue
            for line in path.read_text(encoding="utf-8").splitlines():
                if not line.strip():
                    continue
                record = json.loads(line)
                marker = "legacy:" + table + ":" + hashlib.sha256(line.encode()).hexdigest()
                if database.state(marker, db):
                    continue
                if table == "feedback":
                    db.add(Feedback(insight_id=record["insight_id"], payload=record))
                elif table == "events":
                    db.add(Event(kind=record["kind"], payload=record))
                else:
                    db.add(ToolAudit(request_id=record["request_id"], payload=record))
                database.set_state(marker, True, db)
                counts[table] += 1
        # Учетные записи — один раз: повторный импорт вернул бы удаленных участников из старого JSON.
        if not database.state(AUTH_MARKER, db):
            counts |= import_auth(root, db)
            database.set_state(AUTH_MARKER, {"at": datetime.now(timezone.utc).isoformat(timespec="seconds")}, db)
    return counts


AUTH_MARKER = "legacy:auth_imported"


def _read_key(path: Path, key: str):
    return json.loads(path.read_text(encoding="utf-8"))[key] if path.exists() else None


def import_auth(root: Path, db) -> dict:
    """Перенос учетных записей из JSON-хранилища в той же транзакции; повтор ничего не дублирует."""
    now = datetime.now(timezone.utc)
    counts = {"users": 0, "memberships": 0, "sessions": 0}
    users = _read_key(root / "users.json", "users") or {}
    ids = {}  # user_id из файла -> user_id в базе (дубликаты email по регистру сливаются)
    for u in sorted(users.values(), key=lambda u: u.get("created_at", "")):
        email = u["email"].strip().lower()
        existing = db.scalar(select(AuthUser.user_id).where(AuthUser.email == email))
        if existing is None:
            db.add(AuthUser(user_id=u["user_id"], name=u["name"], email=email, pw_salt=u["pw_salt"], pw_hash=u["pw_hash"],
                            pw_params=u.get("pw_params") or dict(security.LEGACY_PARAMS),
                            created_at=datetime.fromisoformat(u["created_at"]) if u.get("created_at") else now))
            db.flush()
            existing = u["user_id"]
            counts["users"] += 1
        ids[u["user_id"]] = existing
    for m in _read_key(root / "memberships.json", "members") or []:
        email = m["email"].strip().lower()
        user_id = ids.get(m["user_id"]) if m.get("user_id") else None
        counts["memberships"] += db.execute(insert(AuthMembership).values(
            member_id=m["member_id"], company_id=m["company_id"], user_id=user_id, email=email, role=m["role"],
            is_admin=bool(m.get("is_admin")), founder=bool(m.get("founder")), invited_by=m.get("invited_by"),
            created_at=datetime.fromisoformat(m["created_at"]) if m.get("created_at") else now)
            .on_conflict_do_nothing().returning(AuthMembership.member_id)).first() is not None
    ttl = timedelta(hours=config.session_ttl_hours())
    for token_hash, s in (_read_key(root / "sessions.json", "sessions") or {}).items():
        expires = datetime.fromtimestamp(s["expires_at"], timezone.utc)
        user_id = ids.get(s["user_id"])
        if expires <= now or user_id is None:
            continue  # истекшие и сессии неперенесенных пользователей не нужны
        counts["sessions"] += db.execute(insert(AuthSession).values(
            token_hash=token_hash, user_id=user_id, created_at=now, expires_at=min(expires, now + ttl), last_seen=now)
            .on_conflict_do_nothing().returning(AuthSession.token_hash)).first() is not None
    return counts


def import_auth_once(root: Path | None = None) -> dict | None:
    """При старте: перенести учетные записи из RUNTIME_DIR один раз. Потом файлы не читаются — иначе
    удаленный участник вернулся бы из старого JSON. Исходные файлы не удаляются."""
    root = root or config.runtime_dir()
    with database.session() as db:
        db.execute(select(func.pg_advisory_xact_lock(72810406)))
        if database.state(AUTH_MARKER, db):
            return None
        counts = import_auth(root, db) if root.exists() else {"users": 0, "memberships": 0, "sessions": 0}
        database.set_state(AUTH_MARKER, {"at": datetime.now(timezone.utc).isoformat(timespec="seconds"), **counts}, db)
    return counts


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--path", required=True, type=Path)
    args = p.parse_args()
    print(json.dumps(import_runtime(args.path), indent=2))
