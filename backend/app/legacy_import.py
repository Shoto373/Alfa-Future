"""Explicit, idempotent import of an existing JSON runtime into PostgreSQL.

Source files are read only. Imported insights are archived with an obsolete
cache version; new requests are regenerated by the current checked pipeline.
The whole import commits together or rolls back on invalid references.
"""
import argparse
import hashlib
import json
from pathlib import Path
from datetime import datetime

from sqlalchemy import select, func
from sqlalchemy.dialects.postgresql import insert
from app.models import Company, News, Insight, Feedback, Event, ToolAudit

from app import database


def import_runtime(root: Path) -> dict:
    root = root.resolve(strict=True)
    counts = {"companies": 0, "news": 0, "insights": 0, "feedback": 0, "events": 0, "audit": 0}
    def read(path):
        return json.loads(path.read_text(encoding="utf-8"))
    with database.session() as db:
        db.execute(select(func.pg_advisory_xact_lock(72810405)))
        path = root / "companies.json"
        if path.exists():
            for c in read(path)["companies"]:
                counts["companies"] += db.execute(insert(Company).values(company_id=c["company_id"],
                    sector=c["sector"], revenue=c.get("revenue"), payload=c).on_conflict_do_nothing()).rowcount
        path = root / "news.json"
        if path.exists():
            for n in read(path):
                counts["news"] += db.execute(insert(News).values(news_id=n["news_id"],
                    published_at=datetime.fromisoformat(n["published_at"]), kind=n["kind"], payload=n)
                    .on_conflict_do_nothing()).rowcount
        for path in sorted((root / "insights").glob("ins-*.json")):
            ins = read(path)
            ins["quality"] = {"passed": False, "attempts": ins.get("quality", {}).get("attempts", 1), "checks": [
                {"name": "legacy_import", "passed": False, "detail": "Архивный разбор; требуется пересчет текущей версией"}]}
            counts["insights"] += db.execute(insert(Insight).values(insight_id=ins["insight_id"],
                company_id=ins["company_id"], news_id=ins["news_id"], role=ins["role"],
                created_at=datetime.fromisoformat(ins["created_at"]), cache_version="legacy", payload=ins)
                .on_conflict_do_nothing()).rowcount
        for filename, table in (("feedback.jsonl", "feedback"), ("events.jsonl", "events"), ("audit.jsonl", "audit")):
            path = root / filename
            if not path.exists():
                continue
            for line in path.read_text(encoding="utf-8").splitlines():
                if not line.strip():
                    continue
                record = json.loads(line)
                marker = "legacy:" + table + ":" + hashlib.sha256(line.encode()).hexdigest()
                if database.state(marker, db):
                    continue
                if table == "feedback":
                    db.add(Feedback(insight_id=record["insight_id"], payload=record))
                elif table == "events":
                    db.add(Event(kind=record["kind"], payload=record))
                else:
                    db.add(ToolAudit(request_id=record["request_id"], payload=record))
                database.set_state(marker, True, db)
                counts[table] += 1
    return counts


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--path", required=True, type=Path)
    args = p.parse_args()
    print(json.dumps(import_runtime(args.path), indent=2))
