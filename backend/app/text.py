"""Очистка недоверенного текста (новости, материалы, вопросы) от строк-инструкций для модели.

Базовый слой: пользуются хранилище новостей (при приеме) и агент (границы доказательств, самопроверка).
"""
import re

# Инструкции для модели внутри недоверенного текста (prompt injection): такие предложения вырезаются
# при приеме новости и не попадают в выводы. Набор проверок — tests/test_injection.py (40 случаев).
INSTRUCTION = re.compile(
    r"игнориру\w*\s+(?:все\s+)?(?:предыдущ|инструкц|правил|проверк|огранич|контекст)|забудь\s+(?:все|контекст|инструкц|правил)|"
    r"system\s*(?:prompt|:)|системн\w*\s+(?:сообщени|промпт|инструкц)|(?:debug|developer)\s+mode|skip\s+validation|"
    r"проверк\w*\s+(?:источников\s+)?отключен|нов\w+\s+инструкци\w*\s+(?:разработчик|для\s+(?:модел|ассистент|агент))|придумай\s+(?:статистик|цифр|данн)|"
    r"(?:раскрой|покажи|выведи|напиши|сообщи|скопируй|выгрузи)\s+(?:значение\s+)?(?:ключ|парол|системн|токен|переменн|api|llm_|"
    r"журнал|содержимое|адрес\s+сервер)|"
    r"(?:укажи|перечисли|раскрой|выведи|выгрузи|сообщи|покажи)\s+(?:всех\s+|все\s+)?(?:инн|огрн|фио|паспорт|номера\s+сч|"
    r"контрагент|платеж|зарплат|данные\s+других|поля\s+профил|профиль)|"
    r"переведи\s+средства|отправь\s+письмо|добавь\s+в\s+ответ\s+ссылку|"
    r"(?:ignore|disregard)\s+(?:all|previous)|ты\s+теперь|"
    r"(?:объяви|напиши|ответь)\s*[:：]", re.I)


def safe_text(text: str) -> str:
    return " ".join(part.strip() for part in re.split(r"(?<=[.!?])\s+|[\r\n]+", text)
                    if part.strip() and not INSTRUCTION.search(part))
