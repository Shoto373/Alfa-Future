"""False positives found during the live RSS acceptance, paraphrased fixtures."""
import pytest

from app.news.classifier import classify


@pytest.mark.parametrize("title,text", [
    ("Губернатором стал мэр города", "Бывший мэр стал главой региона. Указ о назначении опубликован сегодня."),
    ("Фильм вышел в прокат", "Новый фильм вышел в кинопрокат. На премьере выступил режиссер."),
    ("Артист внес вклад в развитие театра", "В театре состоялась церемония награждения артистов за вклад в культуру."),
    ("Президент прибыл на съезд артистов", "Президент прибыл в театр и вручил награду артистам за работу."),
    ("Религиозная организация запретила публичные комментарии", "Священнослужителям запретили комментировать события без разрешения руководства."),
    ("В стране запретят несогласованные протесты", "Власти обсуждают запрет публичных протестных мероприятий."),
    ("Министр посоветовал жить экономнее", "Министр напомнил о состоянии государственного бюджета и призвал к экономии."),
    ("Обсуждается статус творческих союзов", "Изменения позволят расширить права участников и формировать госзаказ."),
    ("Сервис отменил уборку для гостей", "Платформа аренды жилья обновила правила проживания для гостей при выезде."),
    ("Готовится международный форум", "Участники заявили о стремлении укреплять сотрудничество в сфере энергетики."),
])
def test_non_business_context_does_not_receive_a_business_topic(title, text):
    assert classify(title, text).topic_keys() == []


@pytest.mark.parametrize("title,text,topic", [
    ("Цены на сталь выросли", "Металлургические предприятия повышают цены на стальной прокат.", "metals_steel"),
    ("Банки повысили ставки по вкладам", "Банковские вклады стали доходнее на фоне роста ключевой ставки.", "deposits"),
    ("Прибыль компаний снизилась", "Сальдированная прибыль предприятий снизилась, выручка остается стабильной.", "corporate_finance"),
    ("Введены санкции против экспортеров", "Санкции затрагивают экспортные платежи и поставки товаров.", "sanctions_geopolitics"),
])
def test_business_meaning_is_preserved(title, text, topic):
    assert topic in classify(title, text).topic_keys()
